// Writes src/shapes.css: the generated card outlines (lib/randomShape.js) as static CSS classes,
// one per card — `.shape-<page>-<cell>` — each setting --shape, --shape-inner and --shape-ring.
// Cards name their outline with a class instead of carrying it in a style attribute.
//
// The outlines are seeded, so this is deterministic: run `npm run shapes` again only after changing
// a seed, a cell size (lib/bentoShapes.js) or the generator itself, and commit the result.
import { writeFileSync } from 'node:fs'
import { bentoShapes } from '../src/lib/bentoShapes.js'
import { seedFor } from '../src/lib/seed.js'

// Which cells each bento page uses (Work: a–h plus More work's i–o, Info: a–f).
const BENTO_PAGES = { work: 'abcdefghijklmno', about: 'abcdef' }

const rules = []
const add = (name, shape) =>
  rules.push(
    `.shape-${name} {\n  --shape: ${shape['--shape']};\n  --shape-inner: ${shape['--shape-inner']};\n  --shape-ring: ${shape['--shape-ring']};\n}`,
  )

for (const [page, cells] of Object.entries(BENTO_PAGES)) {
  const shapes = bentoShapes(seedFor(page))
  for (const id of cells) add(`${page}-${id}`, shapes[id])
}

const header =
  '/* GENERATED by scripts/generate-shapes.mjs (`npm run shapes`) — do not edit by hand.\n' +
  '   The card outlines from lib/randomShape.js, one class per card. */\n\n'
writeFileSync(new URL('../src/shapes.css', import.meta.url), header + rules.join('\n\n') + '\n')
console.log(`src/shapes.css: ${rules.length} outlines`)
